/**
 * Retorna o <svg> de um ícone (mesmo markup da página de referência).
 *
 * @param string     $name Nome do ícone (chave de procon_icon_paths()).
 * @param int|null   $size Largura/altura em px; null deixa o tamanho para o CSS.
 * @param string     $fill Cor de preenchimento.
 */
function procon_icon( $name, $size = null, $fill = 'currentColor' ) {
	$paths = procon_icon_paths();
	if ( ! isset( $paths[ $name ] ) ) {
		return '';
	}
	$dims = $size ? sprintf( ' width="%1$d" height="%1$d"', $size ) : '';
	return sprintf(
		'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"%1$s fill="%2$s" aria-hidden="true" focusable="false"><path d="%3$s"/></svg>',
		$dims,
		esc_attr( $fill ),
		esc_attr( $paths[ $name ] )
	);
}
